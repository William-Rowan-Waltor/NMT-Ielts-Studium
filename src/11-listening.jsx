// Offline dictation micro-drill (R12) — trains the two most-missed Listening skills:
// hearing number strings and spelling words correctly. Uses the browser TTS (speakText),
// no AI/backend. Self-contained state.
const DICT_WORDS = ["Cambridge","Edinburgh","Newcastle","Birmingham","Brighton","receipt","accommodation","restaurant","Wednesday","February","library","stationery","colleague","queue","rhythm","necessary","definitely","environment","government","beautiful","comfortable","temperature","vegetable","university","appointment"];
const _normDict = s => String(s||"").toLowerCase().replace(/[^a-z0-9]/g,"");
function makeDictItems(mode, n=5){
  const items=[];
  for(let i=0;i<n;i++){
    const spell = mode==="spell" || (mode==="mixed" && Math.random()<0.5);
    if (spell){ const w=DICT_WORDS[Math.floor(Math.random()*DICT_WORDS.length)]; items.push({type:"spell", speak:w, answer:w, hint:"a word — type it with correct spelling"}); }
    else { const len=6+Math.floor(Math.random()*5); let d=""; for(let k=0;k<len;k++) d+=Math.floor(Math.random()*10); items.push({type:"number", speak:d.split("").join(", "), answer:d, hint:"a number — type the digits"}); }
  }
  return items;
}
