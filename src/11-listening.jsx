function isListeningAnswerCorrect(question, answer) {
  if (question.type === "multiple_choice") {
    const expected = [question.answer, ...(question.acceptedAnswers||[])].map(listeningChoiceValue);
    const given = listeningChoiceValue(answer);
    if (!given) return false;
    if (expected.some(x=>String(x).toUpperCase()===String(given).toUpperCase())) return true;
    return expected.some(x=>normalizeListeningAnswer(x)===normalizeListeningAnswer(given));
  }
  if (question.type === "multiple_choice_multiple") {
    const expected = splitListeningAnswerList(question.answer).map(x=>listeningChoiceValue(x).toUpperCase()).sort();
    const given = splitListeningAnswerList(answer).map(x=>listeningChoiceValue(x).toUpperCase()).sort();
    return expected.length > 0 && expected.length === given.length && expected.every((x,i)=>x===given[i]);
  }
  const limit = LISTENING_COMPLETION_TYPES.includes(question.type) ? listeningWordLimit(question) : null;
  if (limit && countListeningAnswerWords(answer) > limit) return false;
  const expected = Array.isArray(question.acceptedAnswers) && question.acceptedAnswers.length
    ? [question.answer, ...question.acceptedAnswers]
    : [question.answer];
  const given = normalizeListeningAnswer(answer);
  if (!given) return false;
  return expected.some(x=>normalizeListeningAnswer(x)===given);
}

function inferListeningMistake(question, answer) {
  const raw = String(Array.isArray(answer) ? answer.join(", ") : (answer||"")).trim();
  const expected = String(Array.isArray(question.answer) ? question.answer.join(", ") : question.answer||"").trim();
  if (!raw) return "Blank answer - likely missed the key moment in the audio.";
  if (LISTENING_COMPLETION_TYPES.includes(question.type)) {
    const limit = listeningWordLimit(question);
    if (limit && countListeningAnswerWords(raw) > limit) return `Word limit issue - this item allows ${limit} word${limit>1?"s":""}.`;
    if (normalizeListeningAnswer(raw).replace(/s$/,"") === normalizeListeningAnswer(expected).replace(/s$/,"") && normalizeListeningAnswer(raw) !== normalizeListeningAnswer(expected)) {
      return "Singular/plural or exact-form issue - IELTS Listening marks exact answers strictly.";
    }
    if (normalizeListeningAnswer(raw).includes(normalizeListeningAnswer(expected)) || normalizeListeningAnswer(expected).includes(normalizeListeningAnswer(raw))) {
      return "Incomplete or over-complete answer - the key word is close, but the final answer form is not exact.";
    }
    return "Detail or spelling issue - review the evidence line and listen for the exact words.";
  }
  if (question.type === "multiple_choice" || question.type === "multiple_choice_multiple") {
    return "Distractor issue - the chosen option is plausible, but the evidence supports another option.";
  }
  if (question.type === "matching" || question.type === "map_labeling") {
    return "Reference tracking issue - review the sequence of directions, speakers, or labels.";
  }
  return "Comprehension issue - compare your answer with the evidence line.";
}

function validateListeningTest(testData) {
  const issues = [];
  if (!testData?.transcript) issues.push("Missing transcript.");
  if (!testData?.source?.usage) issues.push("Missing source usage metadata.");
  (testData?.questions || []).forEach(q=>{
    if (!q.prompt) issues.push(`Q${q.number}: missing prompt.`);
    if (q.answer === "" || q.answer === null || q.answer === undefined) issues.push(`Q${q.number}: missing answer.`);
    if ((q.type === "multiple_choice" || q.type === "multiple_choice_multiple") && (!q.options || q.options.length < 3)) issues.push(`Q${q.number}: not enough options.`);
    const limit = listeningWordLimit(q);
    if (limit && countListeningAnswerWords(q.answer) > limit) issues.push(`Q${q.number}: answer exceeds word limit.`);
    if (!q.evidenceQuote && q.evidenceStart === null && q.evidenceStart === undefined) issues.push(`Q${q.number}: no evidence marker.`);
  });
  return {
    issues,
    score: Math.max(0, 100 - issues.length * 8)
  };
}

function normalizeListeningTest(raw, fallbackTopic, fallbackDifficulty, fallbackFormat, fallbackMode = "mini", fallbackPart = 1) {
  const selectedPart = Number(raw?.part || fallbackPart || 1);
  const rawSections = Array.isArray(raw?.sections) && raw.sections.length
    ? raw.sections
    : [{
        id: "part-1",
        part: selectedPart,
        title: raw?.title || listeningPartMeta(selectedPart).title,
        context: listeningPartMeta(selectedPart).context,
        transcript: raw?.transcript || "",
        transcriptSegments: raw?.transcriptSegments || raw?.segments || [],
        questions: raw?.questions || []
      }];

  let nextNumber = 1;
  const sections = rawSections.map((section,index)=>{
    const part = Number(section?.part || section?.number || selectedPart || index + 1);
    const meta = listeningPartMeta(part);
    const transcript = section?.transcript || section?.text || raw?.transcript || "";
    const shell = {
      id: section?.id || `part-${part}`,
      index,
      part,
      number: part,
      title: section?.title || meta.title,
      context: section?.context || meta.context,
      transcript,
      transcriptSegments: normalizeListeningSegments(section?.transcriptSegments || section?.segments, transcript),
      paragraphs: [transcript],
      headings: [],
      features: [],
      vocabulary: []
    };
    const __rawQs = Array.isArray(section?.questions) ? section.questions : [];
    // Group same question TYPES together (IELTS lays types out in contiguous blocks). Stable by
    // first-appearance order so the intended sequence is kept while same types cluster.
    const __typeOrder = [];
    __rawQs.forEach(q=>{ const t=String(q?.type||"other"); if(!__typeOrder.includes(t)) __typeOrder.push(t); });
    const __grouped = __rawQs.map((q,i)=>({q,i}))
      .sort((a,b)=> (__typeOrder.indexOf(String(a.q?.type||"other")) - __typeOrder.indexOf(String(b.q?.type||"other"))) || (a.i-b.i))
      .map(x=>x.q);
    const questions = __grouped
      .map((q,i)=>normalizeListeningQuestion(q, i, shell, nextNumber++))
      .filter(q=>q.prompt && q.answer !== "");
    return {
      ...shell,
      questionRange: questions.length ? [questions[0].number, questions[questions.length-1].number] : [nextNumber, nextNumber],
      questions
    };
  });

  const questions = sections.flatMap(s=>s.questions);
  const transcript = sections.map(s=>s.transcript).filter(Boolean).join("\n\n");
  const source = normalizeListeningSource(raw || {});

  return {
    id: raw?.id || Date.now().toString(36),
    title: raw?.title || `Listening: ${fallbackTopic}`,
    format: raw?.format || fallbackFormat,
    topic: raw?.topic || fallbackTopic,
    level: `Band ${fallbackDifficulty}`,
    testMode: raw?.testMode || fallbackMode,
    audioUrl: raw?.audioUrl || raw?.audio_url || "",
    source,
    sourceNote: LISTENING_SOURCE_POLICY,
    transcript,
    transcriptSegments: sections.flatMap(s=>s.transcriptSegments),
    durationSeconds: raw?.durationSeconds || LISTENING_MODE_META[fallbackMode]?.duration || 600,
    sections,
    questions,
    quality: null
  };
}

function listeningEstimatedBand(score, total) {
  if (!total) return 0;
  const raw40 = total === 40 ? score : Math.round((score / total) * 40);
  if (raw40 >= 39) return 9.0;
  if (raw40 >= 37) return 8.5;
  if (raw40 >= 35) return 8.0;
  if (raw40 >= 33) return 7.5;
  if (raw40 >= 30) return 7.0;
  if (raw40 >= 27) return 6.5;
  if (raw40 >= 23) return 6.0;
  if (raw40 >= 19) return 5.5;
  if (raw40 >= 15) return 5.0;
  if (raw40 >= 13) return 4.5;
  return raw40 > 0 ? 4.0 : 0;
}

