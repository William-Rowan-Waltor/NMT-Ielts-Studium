    sourceUrl:inputUrl,
    audioUrl:inputUrl,
    transcript:"",
    transcriptSegments:[],
    source:{sourceName,license:"user_provided_personal_use",usage:"personal_non_commercial_study",commercialUseAllowed:false,redistributionAllowed:false,attribution:inputUrl},
