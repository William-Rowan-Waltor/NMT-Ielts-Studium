function listeningPartMeta(part) {
  return LISTENING_PARTS.find(p=>p.part===Number(part)) || LISTENING_PARTS[0];
}

function listeningTypeLabel(id) {
  return (LISTENING_QUESTION_TYPES.find(t=>t.id===id)?.label || id || "Listening");
}

function normalizeListeningAnswer(value) {
  return String(value||"")
    .toLowerCase()
    .replace(/[.,;:!?()[\]"']/g," ")
    .replace(/\s+/g," ")
    .trim();
}

function splitListeningAnswerList(value) {
  if (Array.isArray(value)) return value.map(x=>String(x).trim()).filter(Boolean);
  return String(value||"").split(/[,;/\s]+/).map(x=>x.trim()).filter(Boolean);
}

function countListeningAnswerWords(value) {
  const clean = String(value||"").trim().replace(/\s+/g," ");
  return clean ? clean.split(" ").length : 0;
}

function listeningWordLimit(question) {
  if (Number(question.wordLimit) > 0) return Number(question.wordLimit);
  const text = `${question.instruction||""} ${question.prompt||""}`.toUpperCase();
  if (text.includes("NO MORE THAN ONE WORD")) return 1;
  if (text.includes("NO MORE THAN TWO WORDS")) return 2;
  if (text.includes("NO MORE THAN THREE WORDS")) return 3;
  return null;
}

function listeningChoiceParts(option, index = 0) {
  const text = String(option||"").trim();
  const m = text.match(/^([A-Z])\s*[\.\)]\s*(.*)$/i);
  if (m) return {value:m[1].toUpperCase(), label:m[2] || text, raw:text};
  return {value:String.fromCharCode(65 + index), label:text, raw:text};
}

function listeningChoiceValue(value) {
  const text = String(value||"").trim();
  const m = text.match(/^([A-Z])(?:\s*[\.\)]|\s*$)/i);
  return m ? m[1].toUpperCase() : text;
}

function normalizeListeningOptions(options) {
  if (Array.isArray(options)) return options.map(x=>String(x||"").trim()).filter(Boolean);
  if (options && typeof options === "object") {
    return Object.keys(options).sort().map(k=>`${String(k).toUpperCase()}. ${options[k]}`);
  }
  return [];
}

function parseListeningTimestamp(value) {
  if (typeof value === "number" && Number.isFinite(value)) return value;
  if (typeof value !== "string") return null;
  const parts = value.trim().split(":").map(Number);
  if (parts.some(x=>Number.isNaN(x))) return null;
  if (parts.length === 2) return parts[0] * 60 + parts[1];
  if (parts.length === 3) return parts[0] * 3600 + parts[1] * 60 + parts[2];
  return null;
}

function formatListeningTime(seconds) {
  if (seconds === null || seconds === undefined || Number.isNaN(Number(seconds))) return "";
  const s = Math.max(0, Math.floor(Number(seconds)));
  const mm = String(Math.floor(s/60)).padStart(2,"0");
  const ss = String(s%60).padStart(2,"0");
  return `${mm}:${ss}`;
}

function listeningTimestampRange(question) {
  const start = parseListeningTimestamp(question.evidenceStart ?? question.evidenceTimestamp ?? question.evidence_timestamp_sec);
  const end = parseListeningTimestamp(question.evidenceEnd);
  if (start === null && end === null) return "";
  if (start !== null && end !== null) return `${formatListeningTime(start)}-${formatListeningTime(end)}`;
  return formatListeningTime(start ?? end);
}

function isDirectListeningAudioUrl(url) {
  const clean = String(url||"").trim();
  if (!clean) return false;
  if (/^(blob:|data:audio\/)/i.test(clean)) return true;
  return /^https?:\/\//i.test(clean) && /\.(mp3|m4a|mp4|wav|ogg|oga|aac|webm)(\?|#|$)/i.test(clean);
}

function decodeListeningHtml(text = "") {
  const map = {amp:"&",lt:"<",gt:">",quot:'"',apos:"'","#39":"'"};
  return String(text)
    .replace(/&(#x?[0-9a-f]+|[a-z]+);/gi, (m, entity) => {
      const key = entity.toLowerCase();
      if (map[key]) return map[key];
      if (key.startsWith("#x")) return String.fromCharCode(parseInt(key.slice(2),16));
      if (key.startsWith("#")) return String.fromCharCode(parseInt(key.slice(1),10));
      return m;
    })
    .replace(/\s+/g," ")
    .trim();
}

function listeningUrlTitle(url, fallback = "Listening import") {
  try {
    const parsed = new URL(url);
    const last = decodeURIComponent(parsed.pathname.split("/").filter(Boolean).pop() || "");
    return last || parsed.hostname.replace(/^www\./,"") || fallback;
  } catch {
    return fallback;
  }
}

function listeningSegmentsToTranscript(segments) {
  return (segments||[])
    .map(seg=>`[${formatListeningTime(seg.start || 0)}] ${seg.speaker ? `${seg.speaker}: ` : ""}${seg.text}`)
    .join("\n");
}

function parseListeningYouTubeJson3(raw) {
  const data = JSON.parse(raw);
  return (data.events || [])
    .filter(event=>Array.isArray(event.segs))
    .map((event,index)=>{
      const text = decodeListeningHtml(event.segs.map(seg=>seg.utf8 || "").join(""));
      const start = Number(event.tStartMs || 0) / 1000;
      const duration = Number(event.dDurationMs || 0) / 1000;
      return {id:`yt-${index+1}`,start,end:duration>0?start+duration:null,speaker:"",text};
    })
    .filter(seg=>seg.text);
}

function parseListeningYouTubeXml(raw) {
  const segments = [];
  const re = /<text\b([^>]*)>([\s\S]*?)<\/text>/gi;
  let match;
  while ((match = re.exec(raw))) {
    const attrs = match[1] || "";
    const text = decodeListeningHtml(match[2].replace(/<[^>]+>/g,""));
    const start = Number((attrs.match(/\bstart="([^"]+)"/) || [])[1]);
    const dur = Number((attrs.match(/\bdur="([^"]+)"/) || [])[1]);
    if (Number.isFinite(start) && text) {
      segments.push({id:`yt-${segments.length+1}`,start,end:Number.isFinite(dur)?start+dur:null,speaker:"",text});
    }
  }
  return segments;
}

function extractListeningYouTubeId(input) {
  try {
    const parsed = new URL(input);
    const host = parsed.hostname.replace(/^www\./,"");
    if (host === "youtu.be") return parsed.pathname.split("/").filter(Boolean)[0] || "";
    if (!host.endsWith("youtube.com")) return "";
    if (parsed.searchParams.get("v")) return parsed.searchParams.get("v") || "";
    const parts = parsed.pathname.split("/").filter(Boolean);
    if (["shorts","embed","live"].includes(parts[0])) return parts[1] || "";
  } catch {}
  return "";
}

async function clientFetchListeningText(url) {
  const res = await fetch(url, {mode:"cors", credentials:"omit"});
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  return await res.text();
}

async function clientImportYouTubeCaptions(inputUrl) {
  const videoId = extractListeningYouTubeId(inputUrl);
  if (!videoId) throw new Error("Could not read YouTube video id.");
  const candidates = [
    `https://video.google.com/timedtext?lang=en&v=${encodeURIComponent(videoId)}&fmt=json3`,
    `https://video.google.com/timedtext?lang=en-US&v=${encodeURIComponent(videoId)}&fmt=json3`,
    `https://www.youtube.com/api/timedtext?lang=en&v=${encodeURIComponent(videoId)}&fmt=json3`,
    `https://video.google.com/timedtext?lang=en&v=${encodeURIComponent(videoId)}`
  ];
  for (const candidate of candidates) {
    try {
      const raw = await clientFetchListeningText(candidate);
      if (!raw.trim()) continue;
      let segments = [];
      try { segments = parseListeningYouTubeJson3(raw); }
      catch { segments = parseListeningYouTubeXml(raw); }
      if (segments.length) {
        return {
          ok:true,
          sourceType:"youtube",
          title:"YouTube captions",
          sourceUrl:inputUrl,
          audioUrl:"",
          transcript:listeningSegmentsToTranscript(segments),
          transcriptSegments:segments,
          source:{sourceName:"YouTube",license:"youtube_terms_personal_use",usage:"personal_non_commercial_study",commercialUseAllowed:false,redistributionAllowed:false,attribution:inputUrl},
          warnings:["Fetched in direct-open browser mode. Keep captions private unless you have redistribution rights."]
        };
      }
    } catch {}
  }
  throw new Error("Browser mode could not access YouTube captions.");
}

function collectListeningTedCues(value, out = []) {
  if (!value || typeof value !== "object") return out;
  if (Array.isArray(value)) {
    value.forEach(item=>collectListeningTedCues(item,out));
    return out;
  }
  const text = value.text || value.content || value.subtitle || value.caption;
  const start = value.startTime ?? value.start_time ?? value.start ?? value.time ?? value.startMs;
  if (typeof text === "string" && start !== undefined && start !== null) {
    const numeric = Number(start);
    if (Number.isFinite(numeric)) {
      out.push({id:`ted-${out.length+1}`,start:numeric>10000?numeric/1000:numeric,end:null,speaker:"",text:decodeListeningHtml(text.replace(/<[^>]+>/g,""))});
    }
  }
  Object.values(value).forEach(item=>collectListeningTedCues(item,out));
  return out;
}

async function clientImportTedTranscript(inputUrl) {
  const parsed = new URL(inputUrl);
  const parts = parsed.pathname.split("/").filter(Boolean);
  const talkIndex = parts.indexOf("talks");
  const slug = talkIndex >= 0 ? parts[talkIndex + 1] : "";
  if (!slug) throw new Error("Could not read TED talk slug.");
  const raw = await clientFetchListeningText(`https://www.ted.com/talks/${slug}/transcript.json?language=en`);
  const data = JSON.parse(raw);
  let segments = collectListeningTedCues(data);
  if (!segments.length) throw new Error("TED transcript JSON did not contain readable cues.");
  segments = segments.map((seg,i)=>({...seg,end:segments[i+1]?.start ?? null}));
  return {
    ok:true,
    sourceType:"ted",
    title:data.title || "TED import",
    sourceUrl:inputUrl,
    audioUrl:"",
    transcript:listeningSegmentsToTranscript(segments),
    transcriptSegments:segments,
    source:{sourceName:"TED",license:"CC-BY-NC-ND / TED terms",usage:"personal_non_commercial_study",commercialUseAllowed:false,redistributionAllowed:false,attribution:inputUrl},
    warnings:["TED content is non-commercial and no-derivatives. Keep imports private/local."]
  };
}

